import { test, expect } from '@playwright/test';

test('project prefix updates existing cases and keeps historical code navigation', async ({ page, request }, testInfo) => {
  const headers = { 'X-IDI-Request': '1' };
  const project = await (await request.post('/api/projects', { headers, data: { name: '简称联动浏览器验证', short_prefix: 'PREFIXOLD' } })).json();
  const item = await (await request.post('/api/cases', { headers, data: { project_id: project.id, title: '简称更新保留原案', building: 'A1', unit: '2', room: '902' } })).json();
  const oldCode = 'PREFIXOLD-A1-U2-902-01', newCode = 'PREFIXNEW-A1-U2-902-01';
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: '本地案件', exact: true }).click();
  await page.getByRole('textbox', { name: '搜索案件', exact: true }).fill(oldCode);
  await page.locator(`[data-case-id="${item.id}"] .case-link`).click();
  await expect(page.getByRole('heading', { name: oldCode, exact: true })).toBeVisible();

  await page.locator('.utility-menu summary').click();
  await page.locator('.utility-menu').getByRole('button', { name: '系统设置', exact: true }).click();
  await page.getByRole('row').filter({ hasText: project.name }).getByRole('button', { name: '编辑', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '编辑项目' });
  await expect(editor).toContainText('旧编号仍可用于照片识别与搜索');
  await editor.getByRole('textbox', { name: '项目简称' }).fill('PREFIXNEW');
  await editor.getByRole('button', { name: '保存项目', exact: true }).click();
  await expect(editor).toHaveCount(0);
  await expect(page.getByRole('status')).toContainText('已更新 1 个案件短编号');
  await page.getByRole('button', { name: '返回案件', exact: true }).click();
  await expect(page.getByRole('heading', { name: newCode, exact: true })).toBeVisible();
  await page.locator('.case-code-history summary').click();
  await expect(page.locator('.case-code-history')).toContainText(oldCode);
  await page.getByRole('button', { name: '水印填写内容', exact: true }).click();
  const watermark = page.getByRole('dialog', { name: '工人水印填写内容' });
  await expect(watermark.locator('pre')).toContainText('编号：' + newCode);
  await watermark.getByRole('button', { name: '关闭', exact: true }).last().click();
  await page.getByRole('button', { name: '返回看板', exact: true }).click();
  await page.getByRole('textbox', { name: '搜索案件', exact: true }).fill(oldCode);
  const row = page.locator(`.board-table [data-case-id="${item.id}"]`);
  await expect(row).toContainText(newCode);
  await expect(page.locator('.board-table [data-case-id]')).toHaveCount(1);
  await page.getByRole('textbox', { name: '快速定位案件', exact: true }).fill(oldCode);
  await expect(page.locator('.case-tree button')).toHaveCount(1);
  await expect(page.locator('.case-tree button')).toContainText(newCode);
  await page.locator('.case-tree button').click();
  await expect(page.getByRole('heading', { name: newCode, exact: true })).toBeVisible();
  await page.locator('.case-code-history summary').click();
  await expect(page.locator('.platform-binding')).toBeVisible();
  await page.getByRole('button', { name: '关闭提示', exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath('prefix-history-desktop.png'), fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('.case-code-history')).toContainText(oldCode);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('prefix-history-mobile.png'), fullPage: true, animations: 'disabled' });
  const current = await (await request.get(`/api/cases/${item.id}`)).json();
  expect(current.short_code_aliases).toEqual([oldCode]);
  expect(current.id).toBe(item.id);
  expect(errors).toEqual([]);
});
