import { test, expect } from '@playwright/test';

test('runtime strip shows only automatic-save switch state and read failures without changing settings', async ({ page, request }, testInfo) => {
  const runtime = await (await request.get('/api/operations')).json();
  runtime.worker_enabled = true;
  runtime.storage.state = 'available';
  runtime.model.state = 'healthy';
  runtime.ocr = { enabled: true, installed: true, pending: 0, latest: { state: 'completed', error: null } };
  runtime.platform.connected = true;
  runtime.policy = { rules_enabled: true, auto_drafts: true };
  runtime.channels = [1, 2, 3].map(id => ({ id: String(id), name: '测试入口', enabled: true, error: null, counts: { pending: 0, failed: 0 } }));
  await page.route('**/api/operations', route => route.fulfill({ json: runtime }));
  const uploads = { policy: { enabled: true }, connected: true, write_enabled: true, counts: { needs_fields: 500 } as Record<string, number>, items: [] };
  let release: () => void = () => {}, failed = false;
  const initialResponse = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/workflow/uploads', async route => {
    await initialResponse;
    return route.fulfill(failed ? { status: 503, json: { detail: '暂时无法读取保存进度' } } : { json: uploads });
  });
  const writes: string[] = [], errors: string[] = [];
  page.on('request', request => { if (request.url().includes('/api/') && !['GET', 'HEAD'].includes(request.method())) writes.push(request.method() + ' ' + new URL(request.url()).pathname); });
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.clock.install();
  await page.goto('/');
  const strip = page.getByRole('region', { name: '运行状态', exact: true });
  const saving = strip.getByRole('button', { name: '查看自动保存状态', exact: true });
  await expect(saving).toContainText('正在读取');
  await expect(saving).not.toContainText('已暂停');
  release();
  await expect(strip).toContainText('资料存储：可用');
  await expect(strip).toContainText('本地 OCR：最近识别成功');
  await expect(strip).toContainText('AI：响应有效');
  await expect(strip).toContainText('官网：已连接');
  await expect(strip).toContainText('收图入口：3 项启用');
  await expect(saving).toHaveText('自动保存：已开启');
  await expect(saving).toHaveAttribute('title', '点击查看保存进度');
  await expect(strip.getByRole('checkbox')).toHaveCount(0);
  await expect(page.getByRole('region', { name: '运行详情', exact: true })).toHaveCount(0);
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect(saving).toBeInViewport();
    expect((await strip.boundingBox())!.x).toBeGreaterThanOrEqual(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    if (width <= 390) expect((await page.getByRole('complementary', { name: '快速导航' }).boundingBox())!.x + (await page.getByRole('complementary', { name: '快速导航' }).boundingBox())!.width).toBeLessThanOrEqual(1);
    if (width === 1440) expect((await strip.boundingBox())!.height).toBeLessThanOrEqual(65);
    await page.screenshot({ path: testInfo.outputPath(`runtime-summary-${width}.png`), fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  uploads.counts = { saving: 2 };
  await page.clock.runFor(10000);
  await expect(saving).toHaveText('自动保存：已开启');
  uploads.counts = { awaiting_confirmation: 1 };
  await page.clock.runFor(10000);
  await expect(saving).toHaveText('自动保存：已开启');
  uploads.connected = false;
  await page.clock.runFor(10000);
  await expect(saving).toHaveText('自动保存：已开启');
  await expect(saving).not.toHaveClass(/needs-attention/);
  uploads.policy.enabled = false;
  await page.clock.runFor(10000);
  await expect(saving).toHaveText('自动保存：已暂停');
  failed = true;
  await page.clock.runFor(10000);
  await expect(saving).toHaveText('自动保存：状态读取失败');
  await expect(saving).toHaveAttribute('title', '暂时无法读取保存进度');
  failed = false; uploads.policy.enabled = true; uploads.connected = true; uploads.counts = {};
  await page.clock.runFor(10000);
  await expect(saving).toHaveText('自动保存：已开启');
  await saving.click();
  await expect(page.getByRole('heading', { name: '系统设置', exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: '后台保存进度', exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: '自动保存设置', exact: true })).toHaveCount(0);
  expect(writes).toEqual([]);
  expect(errors).toEqual([]);
});
